// main.cpp — the PhuzzBox app: a pedal at a time (any of pedals.cpp's, chosen in the window) in a
// window of its own, played through the audio interface at the smallest buffer it takes, with no
// DAW and no browser.
//
// The window is a web view (choc::ui::WebView: WKWebView on macOS, WebView2 on Windows, WebKitGTK
// on Linux) showing window.html, which is built from app.html and the site's own modules (every
// pedal's descriptor, shared/params.js, shared/tuner.js, shared/interfaces.js, shared/pedal.css),
// served from the program itself. The audio is RtAudio (CoreAudio, WASAPI, ALSA or JACK) running
// engine.h. The page calls the program through one function, window.phuzz(method, …args);
// Program::call says what the methods are. MIDI (RtMidi, from every input) goes the other way:
// each control or program change is handed to the page as window.phuzzMidi(status, d1, d2), whose
// MIDI card (shared/midi-panel.js) maps it, as on the site. Settings live in a JSON file in the user's
// application-support folder: the audio, the pedal chosen, and each pedal's parameters
// (as "params-<slug>").

