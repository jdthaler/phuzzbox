// main.cpp — the Phuzzbox app: one pedal in a window of its own, played through the audio
// interface at the smallest buffer it takes, with no DAW and no browser.
//
// The window is a web view (choc::ui::WebView: WKWebView on macOS, WebView2 on Windows, WebKitGTK
// on Linux) showing app.html, which is built from the site's own modules (the pedal's descriptor,
// shared/params.js, shared/tuner.js, shared/interfaces.js, shared/pedal.css), served from the
// program itself. The audio is RtAudio (CoreAudio, WASAPI, ALSA or JACK) running engine.h. The
// page calls the program through one function, window.phuzz(method, …args); Program::call says
// what the methods are. Settings live in a JSON file in the user's application-support folder.

