// bundle-app.mjs — the Phuzzbox app's window as one HTML file: native/app/app.js and the site's
// modules it imports (every pedal's descriptor, shared/params.js, tuner.js, interfaces.js) as one
// classic script, with shared/pedal.css, each ready pedal's style.css (its :root scoped to
// :root[data-pedal="<slug>"], which app.js sets) and native/app/app.css, in native/app/app.html's
// frame. One file, because a web view's custom scheme doesn't load ES modules on every platform.
// The result, native/app/window.html, is committed; the app embeds it (native/app/CMakeLists.txt).
//
//   node tools/bundle-app.mjs           writes native/app/window.html
//   node tools/bundle-app.mjs --check   fails if it is stale (test/native-tests.mjs runs this)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PEDALS } from '../shared/registry.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => relative(root, p).split('\\').join('/');

export function bundle(entry) {
  const order = [], seen = new Map();
  function visit(file) {
    if (seen.has(file)) return seen.get(file);
    const name = `__m${seen.size}`;
    seen.set(file, name);
    let src = readFileSync(file, 'utf8');
    const imports = [];
    src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';\s*$/gm, (_, names, from) => {
      const dep = visit(resolve(dirname(file), from));
      imports.push(`const { ${names.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/\s+as\s+/, ': ')).join(', ')} } = ${dep};`);
      return '';
    });
    if (/^\s*import\s/m.test(src)) throw new Error(`${rel(file)}: an import the bundler doesn't read`);
    const exports = [];
    src = src.replace(/^export\s+(async\s+function|function|class|const|let)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, id) => { exports.push(id); return `${kind} ${id}`; });
    if (/^export\s/m.test(src)) throw new Error(`${rel(file)}: an export the bundler doesn't read`);
    src = src.replace(/import\.meta\.url/g, 'location.href');
    order.push(`// ---- ${rel(file)}\nconst ${name} = (() => {\n${imports.join('\n')}\n${src}\nreturn { ${exports.join(', ')} };\n})();\n`);
    return name;
  }
  visit(entry);
  return order.join('\n');
}

export function build() {
  const frame = readFileSync(`${root}/native/app/app.html`, 'utf8');
  const file = (f) => `/* ---- ${f} */\n${readFileSync(`${root}/${f}`, 'utf8')}`;
  const pedals = PEDALS.filter((p) => p.ready).map((p) => file(`${p.id}/style.css`).replace(/:root\b/g, `:root[data-pedal="${p.id}"]`));
  const css = [file('shared/pedal.css'), ...pedals, file('native/app/app.css')].join('\n');
  const js = `'use strict';\n${bundle(`${root}/native/app/app.js`)}`;
  return `<!-- generated by tools/bundle-app.mjs from native/app/app.html, app.js and the site's modules. Do not edit. -->\n${frame.replace('/*STYLES*/', () => css).replace('/*SCRIPT*/', () => js)}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = `${root}/native/app/window.html`, html = build();
  if (process.argv.includes('--check')) {
    const ok = existsSync(out) && readFileSync(out, 'utf8') === html;
    if (!ok) { console.error('native/app/window.html is stale: run node tools/bundle-app.mjs'); process.exit(1); }
  } else { writeFileSync(out, html); console.log('native/app/window.html'); }
}
