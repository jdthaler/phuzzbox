// gen-native-params.mjs — a pedal's parameter and preset tables for the C++, from its JavaScript
// descriptor (the single source of them), its <slug>-info.cmake from the registry, and its
// <slug>-contract.json: what a song saved with its plugin relies on (tools/contract.mjs).
//   node tools/gen-native-params.mjs [slug…]     write them (every ready pedal if none named)
//   node tools/gen-native-params.mjs --check     exit 1 if any is stale (test/native-tests.mjs)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PEDALS, byId } from '../shared/registry.js';
import { params, nativeValue } from '../shared/params.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const cstr = (s) => JSON.stringify(String(s)); // JSON's escapes are C's for these strings
const num = (x) => (Number.isInteger(x) ? `${x}.0` : String(x));

export async function generate(slug) {
  const { PEDAL } = await import(`${root}${slug}/src/${slug}-pedal.js`);
  const reg = byId(slug);
  const ps = params(PEDAL.groups);
  const ident = (id) => id.replace(/[^A-Za-z0-9_]/g, '_');
  let h = `// ${slug}-params.h — generated by tools/gen-native-params.mjs from ${slug}/src/${slug}-pedal.js: do not edit.
#pragma once

#include "phuzzbox/params.h"

namespace ${ident(slug)} {

// each parameter's index in P
enum Param : int {
${ps.map((p, i) => `  ${ident(p.id)} = ${i},`).join('\n')}
  kParamCount = ${ps.length}
};

`;
  for (const p of ps.filter((q) => q.type === 'select')) {
    h += `inline const char *const ${ident(p.id)}Choices[] = {${p.options.map(([, l]) => cstr(l)).join(', ')}};\n`;
  }
  h += `\ninline const phuzzbox::ParamInfo kParams[] = {\n`;
  for (const p of ps) {
    const kind = p.type === 'select' ? 'choice' : p.type === 'checkbox' ? 'toggle' : 'continuous';
    const [min, max, def] = p.type === 'select' ? [0, p.options.length - 1, nativeValue(p, p.def)] : p.type === 'checkbox' ? [0, 1, p.def ? 1 : 0] : [p.min, p.max, p.def];
    const choices = p.type === 'select' ? `, ${ident(p.id)}Choices, ${p.options.length}` : '';
    h += `  {${cstr(p.id)}, ${cstr(p.label)}, ${cstr(p.group)}, phuzzbox::ParamKind::${kind}, ${num(min)}, ${num(max)}, ${num(def)}, ${num(p.step ?? 0)}, ${!!p.log}, ${cstr(p.unit ?? '')}, ${num(p.scale ?? 1)}, ${p.decimals ?? 2}${choices}},\n`;
  }
  h += `};\n\n`;
  const names = Object.keys(PEDAL.presets ?? {});
  names.forEach((name, k) => {
    const vals = Object.entries(PEDAL.presets[name]).map(([id, v]) => {
      const i = ps.findIndex((p) => p.id === id);
      if (i < 0) throw new Error(`${slug}: preset ${name} sets ${id}, which is no parameter`);
      return `{${i}, ${num(nativeValue(ps[i], v))}}`;
    });
    h += `inline const phuzzbox::PresetValue kPreset${k}[] = {${vals.join(', ')}};\n`;
  });
  h += `inline const phuzzbox::Preset kPresets[] = {\n${names.map((n, k) => `  {${cstr(n)}, kPreset${k}, ${Object.keys(PEDAL.presets[n]).length}},`).join('\n')}\n};\n`;
  h += `inline constexpr int kPresetCount = ${names.length};\n`;
  // the parameter an expression pedal moves (the descriptor's expression), for the plugins' MIDI
  h += `inline constexpr int kExpression = ${PEDAL.expression ? ps.findIndex((p) => p.id === PEDAL.expression) : -1};\n\n} // namespace ${ident(slug)}\n`;

  const cmake = `# ${slug}-info.cmake — generated by tools/gen-native-params.mjs from shared/registry.js: do not edit.
set(PHUZZ_NAME "${reg.name}")
set(PHUZZ_VERSION ${reg.version})
set(PHUZZ_AU_SUBTYPE ${reg.plugin.code})
`;
  return { [`native/pedals/${slug}/${slug}-params.h`]: h, [`native/pedals/${slug}/${slug}-info.cmake`]: cmake,
    [`native/pedals/${slug}/${slug}-contract.json`]: contract(slug, PEDAL) };
}

// What a host keeps of the plugin (native/plugin/plugin.cpp): each parameter by id with its kind,
// range, step, scaling and default (VST3 automation is normalised, so the range is part of it), a
// choice's options in order, and the presets in order (the Preset parameter is a position).
export function contract(slug, PEDAL) {
  const ps = params(PEDAL.groups);
  const out = {
    slug,
    params: ps.map((p) => p.type === 'select' ? { id: p.id, kind: 'choice', options: p.options.map(([v]) => v), def: p.def }
      : p.type === 'checkbox' ? { id: p.id, kind: 'toggle', def: !!p.def }
        : { id: p.id, kind: 'continuous', min: p.min, max: p.max, step: p.step ?? 0, log: !!p.log, def: p.def }),
    presets: Object.entries(PEDAL.presets ?? {}).map(([name, values]) => ({ name, values })),
  };
  // one parameter or preset to a line, so a diff shows what changed
  const rows = (xs) => xs.map((x) => `  ${JSON.stringify(x)}`).join(',\n');
  return `{"slug": ${JSON.stringify(slug)},\n "params": [\n${rows(out.params)}\n ],\n "presets": [\n${rows(out.presets)}\n ]}\n`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const slugs = args.filter((a) => !a.startsWith('--'));
  let stale = 0;
  for (const slug of slugs.length ? slugs : PEDALS.filter((p) => p.ready).map((p) => p.id)) {
    for (const [file, text] of Object.entries(await generate(slug))) {
      const path = root + file;
      const old = existsSync(path) ? readFileSync(path, 'utf8') : null;
      if (old === text) continue;
      if (check) { console.log(`stale: ${file}`); stale++; } else { writeFileSync(path, text); console.log(`wrote ${file}`); }
    }
  }
  if (stale) process.exit(1);
}
